"use client";

import { LogOut } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Dialog } from "@/components/ui/dialog";
import { DemoControls } from "./demo-controls";

/**
 * The one place that identifies the demonstration environment (owner decision, 14 Nov):
 * no labels elsewhere, but always one tap away from the account card.
 */
export function EnvironmentDialog({
  open,
  onClose,
  siteId,
  canControl,
  onDone,
  account,
  onSignOut,
}: {
  open: boolean;
  onClose: () => void;
  siteId: string;
  canControl: boolean;
  onDone: () => void;
  account: { name: string; role: string };
  onSignOut: () => void;
}) {
  return (
    <Dialog open={open} onClose={onClose} title={account.name} description={account.role}>
      <div className="mb-4 flex items-center justify-between gap-3 rounded-xl bg-surface-muted px-4 py-3">
        <div>
          <p className="text-sm font-semibold">Demonstration environment</p>
          <p className="text-xs text-ink-muted">This workspace runs on the live AquaSentinel platform.</p>
        </div>
        <Button variant="secondary" onClick={onSignOut}>
          <LogOut className="size-4" aria-hidden />
          Sign out
        </Button>
      </div>
      <ul className="space-y-2 text-sm text-ink-muted">
        <li>Readings from MU-01 are generated by the platform until field sensors are installed. Each reading records its source.</li>
        <li>SMS go to a demonstration gateway. They show as &ldquo;Sent&rdquo;; &ldquo;Delivered&rdquo; appears only when an SMS provider confirms delivery.</li>
        <li>Everything else (rules, alerts, incidents, roles, records) works exactly as in operation.</li>
      </ul>
      {canControl && (
        <div className="mt-5 -mx-5 -mb-5 border-t border-line">
          <DemoControls siteId={siteId} onDone={onDone} />
        </div>
      )}
    </Dialog>
  );
}
